// Copies the pure money/cycle maths from src/lib into supabase/functions/_shared/lib so the edge functions (Deno)
// and the app share ONE implementation. Imports are rewritten to relative `.ts` paths, which Deno needs.
// Run after changing any of the files below: `npm run sync-shared`. src/lib/shared-sync.test.ts fails if they drift.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

export const SHARED_FILES = [
  'types',
  'format',
  'category-data',
  'money',
  'sa-calendar',
  'cycle',
  'spending',
  'server-notifications',
  'stokvel',
  'splits',
  'wishlist',
  'stay-ahead',
  'challenges',
  'assistant-declarations',
]

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

export function transform(source) {
  const header = '// GENERATED by scripts/sync-shared.mjs from src/lib — edit the src/lib file, then run `npm run sync-shared`.\n'
  return (
    header +
    source.replace(/from '(?:\.\/|@\/lib\/)([\w-]+)'/g, (_m, name) => {
      if (!SHARED_FILES.includes(name)) throw new Error(`Shared file imports ${name}, which is not shared`)
      return `from './${name}.ts'`
    })
  )
}

export function expected() {
  return SHARED_FILES.map((name) => ({
    name,
    out: join(root, 'supabase/functions/_shared/lib', `${name}.ts`),
    content: transform(readFileSync(join(root, 'src/lib', `${name}.ts`), 'utf8')),
  }))
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  for (const f of expected()) {
    mkdirSync(dirname(f.out), { recursive: true })
    writeFileSync(f.out, f.content)
  }
  console.log(`✓ synced ${SHARED_FILES.length} files to supabase/functions/_shared/lib`)
}
